export function auditLabel(l: Locale, action: string) {
  const key: AdminKey =
    action === 'BOOKING_CREATED'
      ? 'bookingCreated'
      : /CANCELLED|EXPIRED|REJECTED/.test(action) && action.startsWith('BOOKING')
        ? 'bookingClosed'
        : /^ADMIN_|^CONTENT_/.test(action)
          ? 'reviewEvent'
          : /SOS|SAFETY/.test(action)
            ? 'safetyAction'
            : /SUPPORT|CASE_|RESTRICTION|CUSTOMER_BLOCK/.test(action)
              ? 'supportAction'
              : /PAYMENT|REFUND|FEE|CAPTURE/.test(action)
                ? 'paymentAction'
                : /DUTY|TIME_OFF|TIME_BLOCK|SERVICE_UPDATED/.test(action)
                  ? 'availabilityAction'
                  : /BOOKING_|STAFF_/.test(action)
                    ? 'bookingUpdated'
                    : 'systemAction';
  return at(l, key);
}
