export type InvoiceKey = keyof typeof words;
export function it(l: Locale, k: InvoiceKey) {
  return words[k][l === 'ja' ? 0 : l === 'en' ? 1 : 2];
}
export function invoiceLabel(l: Locale, k: string) {
  return k in words ? it(l, k as InvoiceKey) : k;
}
export const isInvoiceKey = (k: string): k is InvoiceKey => k in words;
